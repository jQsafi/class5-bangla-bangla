const chaptersFile = './src/data/chapters.json';
let chapters = JSON.parse(fs.readFileSync(chaptersFile, 'utf8'));

function update(id, title, text, category) {
    const ch = chapters.find(c => parseInt(c.id) === id);
    if(ch) {
        ch.title = title;
        ch.category = category;
        if(category === 'kobita') {
            ch.poemLines = text.split('\n');
            ch.fullText = "";
        } else {
            ch.fullText = text;
            ch.poemLines = [];
        }
    }
}

update(16, "শিক্ষাগুরুর মর্যাদা", ch16Text, "kobita");
